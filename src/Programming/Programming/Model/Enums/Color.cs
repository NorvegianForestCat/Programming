/// <summary>
/// Represents a set of predefined colors.
/// </summary>
public enum Color
{
    /// <summary>
    /// A bright red color.
    /// </summary>
    Red,

    /// <summary>
    /// A vivid green color.
    /// </summary>
    Green,

    /// <summary>
    /// A deep blue color.
    /// </summary>
    Blue,

    /// <summary>
    /// A bright yellow color.
    /// </summary>
    Yellow,

    /// <summary>
    /// A pure white color.
    /// </summary>
    White,

    /// <summary>
    /// A pure black color.
    /// </summary>
    Black,

    /// <summary>
    /// A cyan (blue-green) color.
    /// </summary>
    Cyan
}