/// <summary>
/// Represents a genre of film or cinematic fiction.
/// </summary>
public enum Genre
{
    /// <summary>
    /// A comedy film. Designed to entertain and provoke laughter through humor.
    /// </summary>
    Comedy,

    /// <summary>
    /// A dramatic film. Focuses on emotional themes, character development, and realistic storytelling.
    /// </summary>
    Drama,

    /// <summary>
    /// A thriller film. Characterized by suspense, tension, and excitement, often involving crime or danger.
    /// </summary>
    Thriller,

    /// <summary>
    /// An action film. Features physical stunts, chases, fights, and high-energy sequences.
    /// </summary>
    Action,

    /// <summary>
    /// A horror film. Aims to elicit fear, dread, or shock through supernatural or psychological elements.
    /// </summary>
    Horror,

    /// <summary>
    /// A blockbuster film. Typically a high-budget, large-scale production with broad commercial appeal.
    /// Often overlaps with action, adventure, or sci-fi genres.
    /// </summary>
    Blockbuster
}