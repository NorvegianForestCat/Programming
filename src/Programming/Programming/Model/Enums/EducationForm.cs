/// <summary>
/// Represents the form of education for a student or educational program.
/// </summary>
public enum EducationForm
{
    /// <summary>
    /// Full-time education. Student attends classes during regular working hours.
    /// </summary>
    FullTime,

    /// <summary>
    /// Distance learning. Student studies remotely, typically online, without regular in-person attendance.
    /// </summary>
    Distant,

    /// <summary>
    /// Part-time education. Student attends classes outside full working hours, with reduced academic load.
    /// </summary>
    PartTime,

    /// <summary>
    /// Evening education. Classes are held in the evening, typically after work hours.
    /// </summary>
    Evening
}