namespace InformationSystem.Model
{
    /// <summary>
    /// Represents a set of predefined music genres.
    /// Used to categorize songs by their musical style.
    /// </summary>
    public enum Genre
    {
        /// <summary>
        /// Rock music. Characterized by strong vocals, electric guitars, and steady rhythm.
        /// </summary>
        Rock,

        /// <summary>
        /// New Wave. A genre of rock music that emerged in the late 1970s, often featuring synthesizers and experimental sounds.
        /// </summary>
        NewWave,

        /// <summary>
        /// Reggae. Originated in Jamaica, characterized by offbeat rhythms and socially conscious lyrics.
        /// </summary>
        Reggae,

        /// <summary>
        /// Noise. An experimental genre emphasizing distortion, dissonance, and atonality.
        /// </summary>
        Noise,

        /// <summary>
        /// Metal. Heavy metal music with distorted guitars, powerful drums, and aggressive vocals.
        /// </summary>
        Metal,

        /// <summary>
        /// Folk. Traditional or acoustic music reflecting cultural heritage and storytelling.
        /// </summary>
        Folk,

        /// <summary>
        /// Academic (Classical). Orchestral, operatic, or chamber music rooted in Western classical tradition.
        /// </summary>
        Academic,

        /// <summary>
        /// Country. Originating in the Southern US, features storytelling lyrics and string instruments.
        /// </summary>
        Country,

        /// <summary>
        /// Latin/Latino. Music from Latin America, including salsa, reggaeton, and flamenco.
        /// </summary>
        Latino,

        /// <summary>
        /// Blues. Originated in African-American communities, known for its 12-bar structure and emotional expression.
        /// </summary>
        Blues,

        /// <summary>
        /// R&B (Rhythm and Blues). Combines jazz, gospel, and blues influences with soulful vocals.
        /// </summary>
        RnB,

        /// <summary>
        /// Jazz. Improvisational music with complex harmonies and syncopated rhythms.
        /// </summary>
        Jazz,

        /// <summary>
        /// Chanson. French-style narrative song, often poetic and melancholic.
        /// </summary>
        Chanson,

        /// <summary>
        /// Electronic. Music created using electronic instruments and digital production techniques.
        /// </summary>
        Electronic,

        /// <summary>
        /// Hip-Hop. Urban music culture including rap, DJing, and beatboxing.
        /// </summary>
        HipHop,

        /// <summary>
        /// Funk. Danceable groove-based music with strong bass lines and rhythmic complexity.
        /// </summary>
        Funk,

        /// <summary>
        /// Soul. Combines rhythm and blues with gospel music, known for emotional delivery.
        /// </summary>
        Soul,

        /// <summary>
        /// Disco. Dance-oriented music popular in the 1970s, featuring four-on-the-floor beats.
        /// </summary>
        Disco,

        /// <summary>
        /// Dancehall. A Jamaican genre related to reggae, focused on rhythm and deejaying.
        /// </summary>
        Dancehall,

        /// <summary>
        /// Musical. Songs from stage musicals and theatrical productions.
        /// </summary>
        Musical,

        /// <summary>
        /// Pop. Popular music with accessible melodies and broad commercial appeal.
        /// </summary>
        Pop,

        /// <summary>
        /// Other. Category for genres not explicitly listed.
        /// </summary>
        Other
    }
}